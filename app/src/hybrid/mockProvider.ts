import { InferenceMode } from "firebase/ai";
import { probeNetwork } from "./network";
import type { AskOptions, AssistantAnswer, HybridClient, RouteDecision } from "./types";

function mockSourceForMode(mode: InferenceMode): AssistantAnswer["inferenceSource"] {
  switch (mode) {
    case InferenceMode.ONLY_ON_DEVICE:
    case InferenceMode.PREFER_ON_DEVICE:
      return "mock_on_device";
    case InferenceMode.ONLY_IN_CLOUD:
    case InferenceMode.PREFER_IN_CLOUD:
    default:
      return "mock_in_cloud";
  }
}

function craftMockAnswer(intent: string, mode: InferenceMode, route: RouteDecision): string {
  const path =
    mockSourceForMode(mode) === "mock_on_device"
      ? "ON-DEVICE path (simulated Gemini Nano via Chrome Prompt API)"
      : "IN-CLOUD path (simulated Gemini via Firebase AI Logic)";

  return [
    `## HybridCopilot mock response`,
    ``,
    `**Intent:** ${intent.trim() || "(empty)"}`,
    `**Routed mode:** \`${mode}\``,
    `**Simulated source:** ${path}`,
    `**Network:** ${route.quality} — ${route.reason}`,
    ``,
    `### Runnable answer`,
    `1. Confirm booth laptop is on Chrome ≥139 with Prompt API multimodal flag enabled.`,
    `2. Call \`initializeDeviceModel()\` after a user gesture before the first on-device request.`,
    `3. For weak/offline venues use \`PREFER_ON_DEVICE\` / \`ONLY_ON_DEVICE\`; for strong links use \`PREFER_IN_CLOUD\`.`,
    `4. Read \`response.inferenceSource\` (\`on_device\` | \`in_cloud\`) and show it on the badge — judges need to see hybrid, not cloud-only.`,
    `5. Keep a 30-second offline talking track ready if both paths stall.`,
    ``,
    `_This answer was generated by the local mock provider because Firebase web config keys are missing or \`VITE_FORCE_MOCK=true\`. Wire \`.env.local\` from Firebase Console to hit the real hybrid SDK._`,
  ].join("\n");
}

export function createMockClient(): HybridClient {
  return {
    kind: "mock",
    async probeNetwork() {
      return probeNetwork();
    },
    async ask(intent: string, options: AskOptions = {}): Promise<AssistantAnswer> {
      const route = await probeNetwork();
      const mode = options.forceMode ?? route.mode;

      if (options.onDeviceProgress) {
        for (const step of [0.2, 0.55, 0.9, 1]) {
          await new Promise((r) => setTimeout(r, 40));
          options.onDeviceProgress(step);
        }
      }

      const started = performance.now();
      await new Promise((r) => setTimeout(r, mode.includes("on_device") ? 180 : 320));
      const text = craftMockAnswer(intent, mode, route);

      return {
        text,
        inferenceSource: mockSourceForMode(mode),
        modeUsed: mode,
        latencyMs: Math.round(performance.now() - started),
        provider: "mock",
        route,
      };
    },
  };
}
